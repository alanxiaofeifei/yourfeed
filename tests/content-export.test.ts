import { describe, expect, it } from 'vitest';
import type { ContentItem } from '../shared/types';
import { buildContentMarkdown, markdownFilename, markdownText, shareableSourceUrl } from '../shared/content-export';

const english = (_zh: string, en?: string) => en || _zh;
const item = (patch: Partial<ContentItem> = {}): ContentItem => ({ id: 'saved-story', kind: 'article', platform: 'RSS', sourceId: 'feed-1', sourceName: 'Science journal', title: 'An actual source story', url: 'https://journal.reader.net/story?edition=2&utm_source=feed#findings', summary: 'A publisher excerpt.', body: 'The available source text.', publishedAt: '2026-11-10T01:00:00Z', topics: ['science'], ...patch });

describe('local Markdown exports', () => {
  it('exports cached source text with original attribution and truthful incompleteness labels, without AI notes or feedback', () => {
    const source = item({ liked: true, saved: true, reason: 'Private recommendation reason', analysis: { bullets: ['Private AI bullet'], relevance: 'Private profile association', topics: ['science'], coverage: 'excerpt', references: ['https://journal.reader.net/story'], model: 'test-model' } });
    const before = JSON.stringify(source);
    const result = buildContentMarkdown(source, 'original', english);
    expect(result.filename).toBe('An actual source story-original.md');
    expect(result.markdown).toContain('https://journal.reader.net/story?edition=2#findings');
    expect(result.markdown).toContain('Source: Science journal · RSS');
    expect(result.markdown).toContain('may contain only an excerpt or description');
    expect(result.markdown).toContain('A publisher excerpt.');
    expect(result.markdown).toContain('The available source text.');
    expect(result.markdown).not.toContain('Private');
    expect(JSON.stringify(source)).toBe(before);
  });
  it('never presents video metadata or missing body as a complete transcript or original', () => {
    const video = buildContentMarkdown(item({ kind: 'video', body: undefined, summary: 'Public video description' }), 'original', english).markdown;
    expect(video).toContain('not video, audio, or a full transcript');
    expect(video).toContain('Public video description');
    expect(video).not.toContain('Available body text');
    const metadata = buildContentMarkdown(item({ summary: '', body: undefined }), 'original', english).markdown;
    expect(metadata).toContain('No body text or excerpt is available.');
    const same = buildContentMarkdown(item({ summary: 'One excerpt', body: 'One excerpt' }), 'original', english).markdown;
    expect(same.match(/One excerpt/g)).toHaveLength(1);
  });
  it('exports only an existing AI summary with coverage, model, attribution and safe references', () => {
    const result = buildContentMarkdown(item({ analysis: { bullets: ['First sourced point', 'Second point\nwith continuation'], relevance: 'A fit for your science interest.', topics: ['science'], coverage: 'metadata', references: ['https://journal.reader.net/story', 'javascript:alert(1)', 'https://private.feed.net/notes', 'https://journal.reader.net/story', 'https://api.reader.net/key?api_key=secret'], model: 'demo-model' }, relatedSources: [{ name: 'Other publisher', url: 'https://other.reader.net/story' }] }), 'ai-summary', english, 'https://private.feed.net');
    expect(result.filename).toBe('An actual source story-ai-summary.md');
    expect(result.markdown).toContain('generated by AI');
    expect(result.markdown).toContain('Coverage: Based on metadata');
    expect(result.markdown).toContain('Model: demo\\-model');
    expect(result.markdown).toContain('- Second point\n  with continuation');
    expect(result.markdown).toContain('Why it fits you');
    expect(result.markdown).toContain('https://other.reader.net/story');
    expect(result.markdown).not.toContain('javascript:');
    expect(result.markdown).not.toContain('api_key');
    expect(result.markdown).not.toContain('private.feed.net');
    expect(result.markdown).not.toContain('The available source text.');
    expect(() => buildContentMarkdown(item(), 'ai-summary', english)).toThrow('AI_SUMMARY_UNAVAILABLE');
  });
  it('escapes source-supplied HTML and Markdown active content while retaining readable source characters', () => {
    const output = markdownText('<img src=x onerror=steal()>\n[bad](javascript:steal())\n# H\n<script>evil()</script>\n\u0000end');
    expect(output).not.toContain('<img');
    expect(output).not.toContain('<script');
    expect(output).not.toContain('[bad](');
    expect(output).toContain('\\# H');
    expect(output).toContain('&lt;script');
    expect(output).not.toContain('\u0000');
  });
  it('makes bounded safe Unicode filenames without path traversal or bidi spoofing', () => {
    expect(markdownFilename('../画稿\\path:*?"<>|\u202efile', 'original')).toBe('画稿pathfile-original.md');
    expect(markdownFilename(' .. ', 'ai-summary')).toBe('content-ai-summary.md');
    expect(Array.from(markdownFilename('🌱'.repeat(100), 'original').replace('-original.md', ''))).toHaveLength(80);
  });
});

describe('share original source URLs', () => {
  it('copies publisher links, removes known tracking, preserves story and version identity', () => {
    expect(shareableSourceUrl('https://journal.reader.net/daily?edition=2&utm_campaign=share&fbclid=test#story-2')).toBe('https://journal.reader.net/daily?edition=2#story-2');
    expect(shareableSourceUrl('https://www.youtube.com/watch?v=abcdefghijk&si=tracker')).toBe('https://www.youtube.com/watch?v=abcdefghijk');
    expect(shareableSourceUrl('https://journal.reader.net/daily#story-1')).not.toBe(shareableSourceUrl('https://journal.reader.net/daily#story-2'));
  });
  it.each(['javascript:alert(1)', 'data:text/html,test', 'http://journal.reader.net/story', 'https://user:pass@journal.reader.net/story', 'https://localhost/story', 'https://127.0.0.1/story', 'https://[::1]/story', 'https://metadata.google.internal/story', 'https://journal.reader.net:8080/story', 'https://journal.reader.net/unsubscribe', 'https://journal.reader.net/story?key=secret', 'https://journal.reader.net/story#access_token=secret', 'https://journal.reader.net/story#route?password=secret', 'https://journal.reader.net/with\nnewline'])('rejects unsafe or credential-bearing links: %s', input => {
    expect(shareableSourceUrl(input)).toBeNull();
  });
  it('never substitutes a private feed link for the source link', () => {
    expect(shareableSourceUrl('https://private.feed.net/item/secret', 'https://private.feed.net')).toBeNull();
    const result = buildContentMarkdown(item({ url: 'https://private.feed.net/item/secret' }), 'original', english, 'https://private.feed.net');
    expect(result.markdown).not.toContain('https://private.feed.net');
    expect(result.markdown).toContain('could not be exported safely');
  });
});
